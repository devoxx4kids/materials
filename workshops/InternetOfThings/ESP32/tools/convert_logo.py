#!/usr/bin/env python3
"""Convert the Devoxx4Kids logo into a C header for the workshop firmware.

Usage (from the workshop folder):
    python3 tools/convert_logo.py

Reads src/images/devoxx4kids-logo.png and writes firmware/d4kLogo.h: the logo on a white
background, centred on the 320 x 240 Core2 screen, as runs of RGB565 colours, row by row
(pairs of count, colour; a run never crosses the end of a row). firmware/build.sh copies
the header next to the patched tftPrims.cpp, which draws it at start-up.

Maintainer tool: needs Pillow. Its output is committed.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "images" / "devoxx4kids-logo.png"
HEADER = ROOT / "firmware" / "d4kLogo.h"
SCREEN_W, SCREEN_H = 320, 240
PER_LINE = 12  # numbers per line in the header


def rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def runs(logo: Image.Image) -> list[tuple[int, int]]:
    """The logo on white, as (count, RGB565 colour) runs, row by row."""
    image = Image.new("RGBA", logo.size, (255, 255, 255, 255))
    image.alpha_composite(logo.convert("RGBA"))
    image = image.convert("RGB")
    result = []
    for y in range(image.height):
        row = [rgb565(*image.getpixel((x, y))) for x in range(image.width)]
        start = 0
        for x in range(1, image.width + 1):
            if x == image.width or row[x] != row[start]:
                result.append((x - start, row[start]))
                start = x
    return result


def header_text(logo: Image.Image) -> str:
    width, height = logo.size
    if width > SCREEN_W or height > SCREEN_H:
        raise ValueError(f"the logo is {width} x {height}; it must fit the {SCREEN_W} x {SCREEN_H} screen")
    numbers = [str(n) for run in runs(logo) for n in run]
    lines = [", ".join(numbers[i:i + PER_LINE]) + "," for i in range(0, len(numbers), PER_LINE)]
    return "\n".join([
        "// Devoxx4Kids logo for the workshop start-up screen. Generated by tools/convert_logo.py",
        "// from src/images/devoxx4kids-logo.png: do not edit by hand.",
        "// Runs of RGB565 colours, row by row: count, colour, count, colour...",
        "",
        "#include <stdint.h>",
        "",
        f"#define D4K_LOGO_W {width}",
        f"#define D4K_LOGO_H {height}",
        f"#define D4K_LOGO_X {(SCREEN_W - width) // 2}",
        f"#define D4K_LOGO_Y {(SCREEN_H - height) // 2}",
        "",
        "static const uint16_t d4kLogoRuns[] = {",
        *("\t" + line for line in lines),
        "};",
        "",
    ])


def main() -> int:
    HEADER.write_text(header_text(Image.open(SOURCE)), encoding="utf-8")
    print(f"wrote: {HEADER.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
